/**
 * Why the atomic create-and-approve could not be performed.
 *
 * `ADR-024` item 17's seven kinds must not collapse into one another, and this path can reach
 * more of them than any sibling: a **governed business refusal** (the issue #137 pending-revision
 * rule), **stale input**, **invalid content**, a **designation refusal**, a **`DI-6` advancement
 * failure**, two **integrity backstops** and four **protocol** faults are all separate facts with
 * separate codes, and none is ever reported as another.
 *
 * **`EXHAUSTED_RETRY` is absent**, because `ADR-024` item 12 authorizes no automatic retry and
 * nothing here retries. The `40001`/`40P01` classification below is defensive only.
 */
export type AtomicRevisionFailure =
  /** The supplied instant is not a usable moment. Refused before a transaction is opened. */
  | { readonly code: "INVALID_APPROVAL_INSTANT" }
  /**
   * `ADR-019` — the supplied revision identifier is not usable.
   *
   * Refused before a transaction is opened: a non-string would be silently stringified by the
   * `uuid` cast, and a caller error must surface as a caller error rather than as a storage
   * failure from a cast the server happened to reject.
   */
  | { readonly code: "INVALID_REVISION_IDENTIFIER" }
  /**
   * The proposed content is not a complete, inspectable content set.
   *
   * Judged by the domain's **own** readable-revision guard rather than by a second opinion
   * written here, and **distinct from `PROPOSED_CONTENT_INVALID`**: this is a carrier the rules
   * cannot even inspect, not content that was inspected and found wanting.
   */
  | { readonly code: "INVALID_PROPOSED_CONTENT"; readonly offered: unknown }
  /** No listing is stored under this identifier; no lock is held and nothing was written. */
  | { readonly code: "LISTING_NOT_FOUND" }
  /**
   * The locked listing row exists but cannot be represented.
   *
   * **Never reported as not found**, and never as a caller error: the row is present and the
   * caller supplied nothing wrong — the *stored state* disagrees with the governed model.
   */
  | { readonly code: "STORED_LISTING_UNREADABLE"; readonly failure: ListingHydrationFailure }
  /** `FR-ADM-10`/`FR-ADM-10b` govern revisions of an **approved** listing. */
  | { readonly code: "LISTING_NOT_APPROVED"; readonly status: string }
  /**
   * The issue #137 ruling — refused while the listing has a pending revision.
   *
   * A **governed business refusal**, not a fault: the refusal leaves the approved listing and
   * that pending revision unchanged, and the existing revision must first be approved or
   * rejected (`FR-ADM-10`). Decided **under the lock**, never by the index.
   */
  | { readonly code: "PENDING_REVISION_ALREADY_EXISTS" }
  /**
   * `ADR-023` — the caller's captured token does not equal the listing's current version.
   *
   * Nothing was written and the listing is unchanged. **Distinct from every neighbour**, and in
   * particular never conflated with `APPROVAL_INSTANT_NOT_LATER`: two administrators acting
   * inside one millisecond is a `DI-6` problem, not a stale screen (`ADR-024` item 18).
   */
  | { readonly code: "STALE_LISTING_VERSION" }
  /**
   * `ADR-025` — the proposal would publish a value the policy requires to be private.
   *
   * The **complete** violation array in the policy's own deterministic field order, carried
   * intact and carrying **no value**, exactly as `OP-6` reports it.
   */
  | {
      readonly code: "DESIGNATION_POLICY_REFUSED";
      readonly violations: readonly DesignationViolation[];
    }
  /** `FR-VAL-04`/`FR-VAL-05`/`VR-6` — the proposal fails the before-approval obligations. */
  | {
      readonly code: "PROPOSED_CONTENT_INVALID";
      readonly violations: readonly ValidationViolation[];
    }
  /** `DI-6`/`NFR-DATA-05` — the supplied instant does not advance `lastUpdatedAt`. */
  | { readonly code: "APPROVAL_INSTANT_NOT_LATER" }
  /** Any remaining domain refusal, carried intact rather than restated in a second vocabulary. */
  | { readonly code: "ATOMIC_REVISION_REFUSED"; readonly error: DomainError }
  /** The transient revision insert did not affect exactly one row. Unreachable; reported loudly. */
  | { readonly code: "REVISION_INSERT_PROTOCOL_FAILURE"; readonly detail: string }
  /** `ADR-024` item 8 — zero affected rows under the lock. A protocol fault, never staleness. */
  | { readonly code: "GUARDED_UPDATE_PROTOCOL_FAILURE"; readonly detail: string }
  /** The transient revision was no longer pending when it was removed. */
  | { readonly code: "INVALID_LIFECYCLE_STATE"; readonly detail: string }
  /** More than one row matched a primary-key-guarded statement. Unreachable; reported loudly. */
  | { readonly code: "MULTI_ROW_PROTOCOL_FAILURE"; readonly detail: string }
  /** A revision with this identifier already exists (`listing_revision_pkey`). */
  | { readonly code: "REVISION_ALREADY_EXISTS" }
  /** `DI-11`'s index fired — the backstop, which the protocol should have pre-empted. */
  | { readonly code: "PENDING_UNIQUENESS_CONFLICT" }
  /** `ADR-024` item 14 — another integrity backstop fired. A fault to surface, never retried. */
  | { readonly code: "INTEGRITY_CONFLICT"; readonly sqlState: string; readonly constraint?: string }
  /** `ADR-024` item 13 — classified, **not** retried; nothing in this module retries. */
  | { readonly code: "RETRYABLE_CONFLICT"; readonly sqlState: string }
  /** A stored `timestamptz` the governed parser refused. The query ran; this is not infra. */
  | { readonly code: "STORED_INSTANT_UNREADABLE"; readonly reason: TimestamptzParseFailure }
  /** Everything else — a dead connection, an unrecognised driver error. */
  | StorageFailure;

/**
 * A governed refusal, thrown so the transaction genuinely **rolls back**.
 *
 * Returning a failure `Result` from inside the callback would **commit** it, which on this path
 * is not merely dishonest but destructive: after the insert and the guarded update, a commit
 * would leave a transient revision row and an applied listing behind. This sentinel is what makes
 * that impossible. It never escapes this module.
 */
class AtomicRevisionRefused extends Error {
  constructor(readonly failure: AtomicRevisionFailure) {
    super("the atomic create-and-approve was refused");
    this.name = "AtomicRevisionRefused";
  }
}

/**
 * Translate a domain refusal into this boundary's vocabulary, **preserving the distinctions**.
 *
 * `ADR-024` items 17–18 require the reachable kinds to stay apart, so each is mapped to its own
 * code and the remainder is carried intact rather than flattened. Nothing is re-derived: the
 * domain's own payloads travel unchanged.
 */
function atomicFailureFrom(error: DomainError): AtomicRevisionFailure {
  const code = (error as { readonly code?: unknown }).code;

  if (code === "LISTING_NOT_APPROVED") {
    const status = (error as { readonly status?: unknown }).status;

    return {
      code: "LISTING_NOT_APPROVED",
      status: typeof status === "string" ? status : "unknown",
    } as const;
  }

  if (code === "PENDING_REVISION_ALREADY_EXISTS") {
    return { code: "PENDING_REVISION_ALREADY_EXISTS" } as const;
  }

  if (code === "REVISION_CONTENT_INVALID") {
    return {
      code: "PROPOSED_CONTENT_INVALID",
      violations: (error as { readonly violations: readonly ValidationViolation[] }).violations,
    } as const;
  }

  if (code === "INSTANT_NOT_STRICTLY_LATER") {
    // `ADR-024` item 18: its own code, never stale input.
    return { code: "APPROVAL_INSTANT_NOT_LATER" } as const;
  }

  if (code === "INVALID_INSTANT") {
    return { code: "INVALID_APPROVAL_INSTANT" } as const;
  }

  return { code: "ATOMIC_REVISION_REFUSED", error } as const;
}

/**
 * `ADR-024` step 1 — the `PS-11` lock, taken first and held through commit.
 *
 * `selectAll`, not a projection: `ADR-025` compares against *"the listing's current persisted
 * value"* and the domain operations require the **complete** readable aggregate — status, every
 * content field, publication state and all three timestamps. Reading it in the locking statement
 * rather than a second query is what makes the comparison unforgeable: there is no window between
 * the lock and the read in which a rival could change what is compared. This is
 * `lockListingRow`'s precedent in `revision-approval.ts` and `lockListing`'s in
 * `revision-repository.ts` since issue #207.
 */
async function lockListingRow(trx: Transaction<ListingDatabase>, listingId: string) {
  return await trx
    .selectFrom("listing")
    .selectAll()
    .where("id", "=", listingId)
    .forUpdate()
    .executeTakeFirst();
}

/**
 * Create and approve one revision atomically (`FR-ADM-10b`), under `ADR-024`'s protocol.
 *
 * The caller supplies the listing's identity, the identifier the transient proposal will carry,
 * the token it captured when the administrator's work began, the **complete** proposed content,
 * and the instant. It supplies **no** `Listing` — the authoritative aggregate is the one read
 * under the lock — and **no** role, actor, reason, override, retry count, transaction or clock.
 *
 * Returns the **domain's own** applied `Listing`: the proposal's content, the advanced
 * `lastUpdatedAt`, and the unchanged identity, status, `submittedAt` and publication state. That
 * value is the resulting state `FR-CONF-04` asks for, and it cannot disagree with what was
 * committed because it is not a re-read. **The revision identifier is not part of it.**
 *
 * Nothing supplied is mutated.
 */
export async function createAndApproveRevisionAtomically(
  db: Kysely<ListingDatabase>,
  request: {
    readonly listingId: ListingId;
    readonly revisionId: string;
    readonly baseListingLastUpdatedAt: Instant;
    readonly proposedContent: ListingContent;
    readonly at: Instant;
  },
): Promise<Result<Listing, AtomicRevisionFailure>> {
  const { listingId, revisionId, baseListingLastUpdatedAt, proposedContent, at } = request;

  // Refused before a transaction is opened, so a caller error never takes a lock. The domain
  // refuses a malformed instant too — but a carrier that cannot reach SQL should not be
  // discovered halfway through a locked transaction.
  if (!isInstant(at)) {
    return err({ code: "INVALID_APPROVAL_INSTANT" } as const);
  }

  if (typeof revisionId !== "string" || revisionId === "") {
    return err({ code: "INVALID_REVISION_IDENTIFIER" } as const);
  }

  if (!isInstant(baseListingLastUpdatedAt)) {
    // `ADR-023` item 12 — a missing or unusable token refuses the write. It is the caller's
    // token that is wrong, which is staleness's own vocabulary and not a second code.
    return err({ code: "STALE_LISTING_VERSION" } as const);
  }

  // The transient proposal, built **here** because it never survives the transaction and no
  // caller has any use for it. It carries the caller's **original** token and the complete
  // proposed content, and **no identifier**: `ListingRevision` has no identity field, and
  // `DDM-2` stays open precisely because nothing needs one.
  const proposal: ListingRevision = {
    listingId,
    state: "pending",
    proposedContent,
    baseListingLastUpdatedAt,
  };

  // The domain's **own** readable-revision judgement, not a second opinion: it proves the
  // identity object, the governed state, inspectable content and the exact token carrier. It is
  // also the call that **narrows** the value, so no cast is needed below. Content *validity* —
  // blank, too long, malformed — is `validateBeforeApproval`'s and is not pre-empted here.
  if (!isPendingRevision(proposal)) {
    return err({ code: "INVALID_PROPOSED_CONTENT", offered: proposedContent } as const);
  }

  const pending: PendingListingRevision = proposal;
  const listingText = identifierTextOf(listingId);

  try {
    const applied = await db
      .transaction()
      // `ADR-024` item 1: set explicitly per transaction, never inherited from a server default.
      .setIsolationLevel("read committed")
      .execute(async (trx) => {
        // (1) The `PS-11` lock. FIRST, before any other database state is read, held to commit.
        const listingRow = await lockListingRow(trx, listingText);

        // (2) The listing must exist.
        if (listingRow === undefined) {
          throw new AtomicRevisionRefused({ code: "LISTING_NOT_FOUND" } as const);
        }

        // (3) …and be representable. A row that exists but cannot be read is a different, louder
        // problem than one that is absent, and neither the designation rule nor the domain
        // operations can be asked about it.
        const listing = hydrateListing(listingRow);

        if (!listing.ok) {
          throw new AtomicRevisionRefused({
            code: "STORED_LISTING_UNREADABLE",
            failure: listing.error,
          } as const);
        }

        // (4) The lifecycle check, decided from the locked row — **before** the revision read,
        // which would otherwise be pointless. `revision-approval.ts` reports its own lifecycle
        // at exactly this point, and `ADR-024`'s projection of `status` invites it. The domain
        // enforces the same rule again at step (8); this is not a substitute for it.
        if (listingRow.status !== "approved") {
          throw new AtomicRevisionRefused({
            code: "LISTING_NOT_APPROVED",
            status: listingRow.status,
          } as const);
        }

        // (5) `ADR-024`'s prescribed post-lock revision read, after the listing lock (item 5) and
        // itself locked. A fresh statement snapshot under `READ COMMITTED`, so it observes a
        // preceding participant's committed revision even when that participant only **locked**
        // the listing row — `PS-11`'s visibility requirement, met rather than assumed.
        const existing = await trx
          .selectFrom("listing_revision")
          .select("id")
          .where("listing_id", "=", listingText)
          .where("state", "=", "pending")
          .forUpdate()
          .execute();

        // (6) The issue #137 ruling, decided **under the lock** rather than by `DI-11`'s index
        // (`ADR-024` item 11). A governed refusal: the approved listing and the pending revision
        // are both left exactly as they are, and nothing newly created remains — nothing has
        // been created yet.
        if (existing.length > 0) {
          throw new AtomicRevisionRefused({
            code: "PENDING_REVISION_ALREADY_EXISTS",
          } as const);
        }

        // (7) The stale check, **before any mutation** (`ADR-023` item 12, `ADR-024` item 6). The
        // token is the **caller's original** capture — never recaptured from the row being
        // compared — against the locked listing's current version, by exact epoch-millisecond
        // equality on the same `Instant` carrier, so the comparison cannot drift between
        // representations.
        const current = instantOf(listingRow.last_updated_at);

        if (!current.ok) {
          throw new AtomicRevisionRefused({
            code: "GUARDED_UPDATE_PROTOCOL_FAILURE",
            detail: "the locked listing's last_updated_at is not a usable instant",
          } as const);
        }

        if (!instantEquals(baseListingLastUpdatedAt, current.value)) {
          throw new AtomicRevisionRefused({ code: "STALE_LISTING_VERSION" } as const);
        }

        // (8) `ADR-025`, enforced **before any mutation** and exactly once. The current side is
        // the **locked, stored** listing's content — never the caller's, never a pre-lock read —
        // and the proposed side is the caller's **original** content, unnormalized. Nothing is
        // coerced to private: a widening is refused, with every offending field reported in the
        // rule's own deterministic order. `OP-6`'s precedent exactly.
        const designation = enforceDesignationPolicy(listing.value.content, proposedContent);

        if (!designation.ok) {
          throw new AtomicRevisionRefused({
            code: "DESIGNATION_POLICY_REFUSED",
            violations: designation.error,
          } as const);
        }

        // (9) Admission — the pure domain's `DI-11`, listing-match and approved-listing rules.
        // The collection is `[]` because step (5) has already proved under the lock that no
        // pending revision exists; fabricating a non-empty one would be inventing state.
        const admitted = admitPendingRevision(listing.value, [], pending);

        if (!admitted.ok) {
          throw new AtomicRevisionRefused(atomicFailureFrom(admitted.error));
        }

        // (10) Approval and application — `validateBeforeApproval` exactly as a separately
        // submitted revision meets it (`FR-VAL-04`/`FR-VAL-05`/`VR-6`, no privileged bypass),
        // `withListingContent`'s content application and `DI-6` advancement, and removal of the
        // approved proposal from the collection. **No materiality test**: equal content is an
        // ordinary revision here, exactly as it is through `OP-6` + `OP-10`.
        const resolution = approvePendingRevision(listing.value, admitted.value, at);

        if (!resolution.ok) {
          throw new AtomicRevisionRefused(atomicFailureFrom(resolution.error));
        }

        // `ADR-017` Q-3 — no approved revision row persists, so the collection the domain
        // returns must be empty. Asserted rather than assumed.
        if (resolution.value.revisions.length !== 0) {
          throw new AtomicRevisionRefused({
            code: "MULTI_ROW_PROTOCOL_FAILURE",
            detail: "the domain returned a surviving revision for an approved proposal",
          } as const);
        }

        // (11) The transient pending revision, carrying the **original** captured token — never
        // the value just read. Every value is a bound parameter, the identifier is used exactly
        // as supplied, and there is **no `RETURNING`**: inventing an identity contract is
        // precisely what `DDM-2` leaves open.
        const insertion = await trx
          .insertInto("listing_revision")
          .values(serializePendingRevision(revisionId, pending))
          .executeTakeFirst();

        const insertedRows = Number(insertion.numInsertedOrUpdatedRows ?? 0n);

        if (insertedRows !== 1) {
          throw new AtomicRevisionRefused({
            code: "REVISION_INSERT_PROTOCOL_FAILURE",
            detail: "the transient revision insert did not affect exactly one row",
          } as const);
        }

        // (12) The guarded update — the **original** caller token in the predicate, never a
        // refreshed one and never the approval instant, and only the columns the domain changed.
        const update = await trx
          .updateTable("listing")
          .set(serializeAppliedListingContent(resolution.value.listing))
          .where("id", "=", listingText)
          // The token as a `timestamptz`, through the **same** expression the insert uses. A
          // bound number would be no comparison at all: PostgreSQL cannot compare `timestamptz`
          // to `bigint`, so the predicate would raise `42883` rather than quietly match nothing —
          // and sharing the conversion is what keeps it exact to the millisecond.
          .where(
            "last_updated_at",
            "=",
            timestamptzFromEpochMilliseconds(epochMillisecondsOf(baseListingLastUpdatedAt)),
          )
          .executeTakeFirst();

        const updatedRows = Number(update.numUpdatedRows);

        // (13) Exactly one row. Zero — after the lock was held and the comparison succeeded — is
        // a loud protocol failure and never stale input, which the comparison already ruled out.
        if (updatedRows === 0) {
          throw new AtomicRevisionRefused({
            code: "GUARDED_UPDATE_PROTOCOL_FAILURE",
            detail: "the guarded listing update matched no row under the lock",
          } as const);
        }

        if (updatedRows > 1) {
          throw new AtomicRevisionRefused({
            code: "MULTI_ROW_PROTOCOL_FAILURE",
            detail: "the guarded listing update matched more than one row",
          } as const);
        }

        // (14) Remove the transient proposal, by its adapter-private identifier, with the listing
        // and the pending state as defence in depth: both are implied by the insert, and both
        // make a wrong-row delete impossible even under a later bug. **Exactly one `DELETE`** —
        // `ADR-017` Q-3's removal, inside the applying transaction.
        const deletion = await trx
          .deleteFrom("listing_revision")
          .where("id", "=", revisionId)
          .where("listing_id", "=", listingText)
          .where("state", "=", "pending")
          .executeTakeFirst();

        const deletedRows = Number(deletion.numDeletedRows);

        // (15) `ADR-024`'s classification, followed as written: zero deleted rows means the
        // revision was no longer pending, which is an **invalid lifecycle state** rather than a
        // protocol failure. The insert and the listing update above are rolled back with it.
        if (deletedRows === 0) {
          throw new AtomicRevisionRefused({
            code: "INVALID_LIFECYCLE_STATE",
            detail: "the transient revision was no longer pending when it was removed",
          } as const);
        }

        if (deletedRows > 1) {
          throw new AtomicRevisionRefused({
            code: "MULTI_ROW_PROTOCOL_FAILURE",
            detail: "removing the transient revision matched more than one row",
          } as const);
        }

        // (16) Commit, atomically. The applied listing is the domain's own value, not a re-read,
        // and it carries no revision identity.
        return resolution.value.listing;
      });

    return ok(applied);
  } catch (cause) {
    // A governed refusal: raised inside the transaction so that it rolled back, and carried out
    // here so the caller receives it as an ordinary `Result` rather than an exception.
    if (cause instanceof AtomicRevisionRefused) {
      return err(cause.failure);
    }

    // A governed instant the parser refused is not an infrastructure failure: the query ran.
    if (cause instanceof TimestamptzParseError) {
      return err({ code: "STORED_INSTANT_UNREADABLE", reason: cause.reason } as const);
    }

    const sqlState = sqlStateOf(cause);

    if (sqlState === UNIQUE_VIOLATION) {
      const constraint = constraintOf(cause);

      // Two different facts, told apart by the constraint that fired — never folded together.
      if (constraint === REVISION_IDENTITY_CONSTRAINT) {
        return err({ code: "REVISION_ALREADY_EXISTS" } as const);
      }

      if (constraint === PENDING_UNIQUENESS_CONSTRAINT) {
        // The backstop fired, which means the post-lock read did not pre-empt it. Surfaced as
        // the fault it is — never retried, and never reported as the ordinary `DI-11` refusal.
        return err({ code: "PENDING_UNIQUENESS_CONFLICT" } as const);
      }
    }

    if (
      sqlState === UNIQUE_VIOLATION ||
      sqlState === CHECK_VIOLATION ||
      sqlState === FOREIGN_KEY_VIOLATION
    ) {
      const constraint = constraintOf(cause);

      // Surfaced as the fault it is, never retried (`ADR-024` item 14 classifies all three as
      // non-retryable). The constraint **name** is schema metadata; its contents never appear.
      return err(
        constraint === undefined
          ? ({ code: "INTEGRITY_CONFLICT", sqlState } as const)
          : ({ code: "INTEGRITY_CONFLICT", sqlState, constraint } as const),
      );
    }

    if (sqlState !== undefined && RETRYABLE_CONFLICT_STATES.includes(sqlState)) {
      // Classified defensively, because the server decides which `SQLSTATE` it raises.
      // Classification is **not** a licence to retry, and nothing here retries.
      return err({ code: "RETRYABLE_CONFLICT", sqlState } as const);
    }

    // Anything else — a dead connection, an unrecognised driver error — stays unexpected.
    return err(storageFailure(cause));
  }
}
