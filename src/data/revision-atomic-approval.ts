/**
 * `C9` — `FR-ADM-10b`: create **and** approve a listing revision in one transaction (issue #219).
 *
 * The **fourth and last** of `ADR-024`'s governed `PS-11` write paths, after `OP-6` (issue #195),
 * `OP-10` (issue #197) and `FR-ADM-04` (issue #217). It reuses their protocol shape rather than
 * re-deriving it, and it is a new module for the same reason they are: one file per `PS-11` path.
 *
 * ## What this path is, and what it is not
 *
 * `FR-ADM-10b` is *"a safeguarded exception to the two-step sequence, **within** the revision
 * lifecycle — not a bypass of it and not a direct unvalidated overwrite"*. So the revision
 * lifecycle is genuinely **exercised**: a pending proposal is created, validated, approved,
 * applied and removed — all inside one transaction, which is `ADR-017` Q-3's atomic unit read at
 * the store level. **No direct listing update is manufactured instead.** `ADR-024`'s own
 * `FR-ADM-10b` sequence prescribes the insert, the guarded update and the delete literally, and
 * the transient row is why that ADR records that `DI-11`'s index *"cannot be the serialization
 * mechanism"*.
 *
 * The transient row is **never externally observable**. Every governed path takes the listing
 * lock first and holds it to commit, so a rival blocks from before this insert until after this
 * delete has committed: it sees either no pending row, or a pending row some *other* participant
 * committed — never this one.
 *
 * ## The content is a complete proposal, not a patch
 *
 * `ADR-017` defines a proposal as *"a complete set, not a difference"*, and `ADR-025` rejected
 * *"treat absent values in a complete proposal as patch omission"* in terms, because *"an absent
 * field would silently preserve a public value the administrator believed they had removed"*. So
 * this boundary takes `ListingContent`, and `FR-ADM-04`'s three-state `AdministrativeEdit` is
 * **not** reused here. On this path absence means **removal**.
 *
 * ## Equal content is not a no-op here
 *
 * The issue #213 ruling is scoped in its own text to *"an otherwise valid **`FR-ADM-04`** edit"*
 * against *"the **pending** listing's current content"*. It does not reach this path, and
 * **nothing below short-circuits on material equality.** What governs instead is
 * `FR-ADM-10b`'s own parity clause — *"all validation, authorization, and publication safeguards
 * applicable to a **separately submitted revision**"* — so a proposal equal to the current
 * content behaves exactly as it does through merged `OP-6` + `OP-10`: the revision is created,
 * applied and removed, and `lastUpdatedAt` **advances** under `DI-6`. Neither
 * `createPendingRevision`, `admitPendingRevision`, `approvePendingRevision` nor
 * `approveAndApplyPendingRevision` contains a materiality test, and adding one here would give
 * the atomic path a behaviour the two-step path it must match does not have.
 *
 * `FR-ADM-04` is the opposite case and stays that way: `applyAdministrativeEditToPendingListing`
 * writes nothing on a no-op, because its own ruling says so. The two paths differ because their
 * rulings differ, not because one of them was optimized.
 *
 * ## How the steps are counted
 *
 * Three different counts are correct about different things, and conflating them is how a review
 * argument starts. **Protocol steps** are the numbered decisions below, `(1)`–`(16)`: they include
 * the purely in-memory ones — hydration, the lifecycle decision, the token comparison, the
 * designation rule, the two domain operations and every affected-row check. **Governed SQL
 * statements** are **five**, and only five: the listing lock, the pending-revision read, the
 * revision `INSERT`, the guarded listing `UPDATE` and the revision `DELETE`, between the `BEGIN`
 * that carries the isolation level and the `COMMIT`. **Writes** are **three** of those five.
 * `ADR-024`'s `FR-ADM-10b` block prescribes exactly those five statements in exactly that order;
 * issue #219's step list is the protocol-step count, and the statement suite asserts the
 * statement count. Both are checked, and neither is the other.
 *
 * ## The domain owns every content decision; this module owns the transaction
 *
 * `enforceDesignationPolicy` (`ADR-025`), `admitPendingRevision` (`DI-11`, the approved-listing
 * rule, the listing match) and `approvePendingRevision` (`validateBeforeApproval`,
 * `withListingContent`, `DI-6`, removal of the approved proposal) are the sole authorities on
 * their own rules, and **none of them is restated here**. This module locks, compares the stale
 * token, hands the domain hydrated values, and turns the one value it returns into exactly three
 * statements.
 *
 * ## Revision identity stays here
 *
 * `revisionId` is `ADR-019`'s **application-generated** UUID. It is supplied, never generated by
 * PostgreSQL — migration `001` declares *"no `DEFAULT gen_random_uuid()`, no sequence"* — it
 * never enters `ListingRevision` or any other domain type, it is never returned, never logged,
 * and no `RETURNING` clause exists to surface it. It is used for the insert and for the exact
 * delete, and then discarded. `DDM-2` stays open: this unit needs no revision-identity domain
 * type, because it never addresses one revision among several from outside the adapter.
 *
 * A **duplicate identifier** and a **`DI-11` conflict** are different facts and are reported as
 * `REVISION_ALREADY_EXISTS` and `PENDING_UNIQUENESS_CONFLICT`, told apart by constraint name
 * exactly as `OP-6` tells them apart. Neither is retried.
 *
 * ## What this module does not do
 *
 * No transport, HTTP handler, authorization, role, override, administrator message formatting,
 * audit storage or event, retry, schema, migration, dependency, revision-identity domain type,
 * rejected-history retrieval, retention, purge, `FR-ADM-09`, search or deployment behaviour —
 * and **no production fault-injection hook**. It reads no clock: every instant is supplied.
 */

